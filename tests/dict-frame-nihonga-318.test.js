const EGAZAI = /^https:\/\/www\.e-gazai\.com\/shop\/g\/g\d+\/$/;
const MATUEDA = /^https:\/\/www\.matueda\.com\/\?pid=\d+$/;

const byJan = new Map(JAN_DICTIONARY.map((d) => [d.jan, d]));
const entry = (jan) => {
  const d = byJan.get(jan);
  assert.ok(d, `辞書に ${jan} がありません`);
  return d;
};

test('追加したクサカベ アキーラ・ガッシュ21件が、色名・色番・容量つきで引ける', () => {
  assert.equal(ADDED_JANS.length, 318);
  assert.equal(new Set(ADDED_JANS).size, 318);
  assert.equal(KUSAKABE_JANS.length, 21);
  for (const jan of KUSAKABE_JANS) {
    const d = entry(jan);
    assert.equal(d.maker, 'クサカベ');
    assert.equal(d.category, 'watercolor');
    assert.equal(d.series, 'アキーラ ガッシュ');
    assert.match(d.source, EGAZAI);
    assert.ok(isValid(d.jan));
    assert.ok(d.colorName, `色名なし: ${jan}`);
    assert.match(d.code, /^[AB]-\d{2}$/, `色番が違う: ${jan} ${d.code}`);
    assert.match(d.size, /^(11|20)ml$/);
    assert.match(d.name, /アキーラ ガッシュ/);
  }
  const carmine = entry('4933317600112');
  assert.equal(carmine.colorName, 'カーマイン');
  assert.equal(carmine.code, 'A-11');
  assert.equal(lookupJAN('4933317600112')?.code, 'A-11');

  const hay = dictionaryHaystack(JAN_DICTIONARY);
  const hit = (q) => searchDictionary(JAN_DICTIONARY, q, { limit: 3000, hay }).items.some((d) => NEW_JANS.has(d.jan));
  assert.ok(hit('アキーラ'), 'アキーラで引けない');
  assert.ok(hit('ガッシュ'), 'ガッシュで引けない');
  assert.ok(hit('カーマイン'), '色名で引けない');
  assert.ok(hit('A-11'), '色番で引けない');
});

test('追加した額装・色紙類のメーカーはページの製造元どおりで、プレフィックス登録と一致する', () => {
  // 福井金属工芸（額のまつえだの額装金具）
  for (const jan of ['4947189600507', '4947189661409', '4947189619301', '4947189623100', '4947189671408', '4947189232005']) {
    const d = entry(jan);
    assert.equal(d.maker, '福井金属工芸');
    assert.equal(d.category, 'frame');
    assert.match(d.series, /^フクイ /);
    assert.match(d.source, MATUEDA);
  }
  // 大仙・大額・谷口松雄堂（ページの「製造メーカー」に合わせた）
  assert.equal(entry('4904690119935').maker, '大仙');
  assert.equal(entry('4904690119935').series, '大仙 色紙額（24.2×27.3cm用）');
  assert.equal(entry('4904690405014').maker, '大仙');
  assert.equal(entry('4516722048450').maker, '大額');
  assert.equal(entry('4532742012165').maker, '谷口松雄堂');
  // ミューズのコットン紙（製造元は谷口松雄堂）はミューズの紙として収録
  assert.equal(entry('4532742007598').maker, 'ミューズ');
  assert.equal(entry('4532742007598').colorName, 'さくら');
  assert.equal(entry('4532742007598').size, '10枚入り');
  // すべて、メーカーがプレフィックス表に載っている
  for (const jan of ['4904690119935', '4516722048450', '4532742012165', '4532742007598']) {
    const d = detectMaker(jan);
    const p = JAN_PREFIXES.find((x) => x.prefix === d.prefix);
    assert.ok(p.makers.includes(entry(jan).maker), `${jan} のメーカーがプレフィックスにない`);
  }
});

test('追加分は13桁JAN・実在カテゴリ・https出典で、商品名とシリーズが空でない', () => {
  const catIds = new Set(CATEGORIES.map((c) => c.id));
  for (const jan of ADDED_JANS) {
    const d = entry(jan);
    assert.match(d.jan, /^\d{13}$/);
    assert.ok(isValid(d.jan), `チェックディジット不正: ${d.jan}`);
    assert.ok(catIds.has(d.category), `カテゴリ不正: ${d.jan} ${d.category}`);
    assert.ok(d.name.length > 1, `商品名なし: ${d.jan}`);
    assert.ok(d.series, `シリーズなし: ${d.jan} ${d.name}`);
    assert.ok(d.maker, `メーカーなし: ${d.jan}`);
    assert.match(d.source, /^https:\/\//);
  }
});

function isValid(jan) {
  return calcCheckDigit(jan.slice(0, 12)) === Number(jan[12]);
}
